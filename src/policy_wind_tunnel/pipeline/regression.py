from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

from policy_wind_tunnel.pipeline.triage import TriageReport

Implementation = Callable[[dict[str, Any]], dict[str, Any]]

HEADER = '''"""Regression tests generated by Policy Wind Tunnel for {name}.

Each test pins the behaviour required by the approved policy contract.
Provide a callable `implementation(inputs: dict) -> dict` before running.
"""

implementation = None
'''

TEST_TEMPLATE = '''

def test_{ident}():
    # {summary}
    # Policy clause {clause}
    inputs = {inputs}
    expected = {expected}
    result = implementation(inputs)
    assert {{"outcome": result["outcome"], "reasons": list(result["reasons"])}} == expected
'''


@dataclass
class RegressionResult:
    tests: int
    failing_on_buggy: int
    passing_on_fixed: int
    errors: int = 0


def _identifier(index: int, clause: str, rule_id: str) -> str:
    safe = "".join(ch if ch.isalnum() else "_" for ch in f"{clause}_{rule_id}").lower()
    return f"{index:02d}_{safe}"


def emit_regression_tests(report: TriageReport, contract_name: str) -> str:
    parts = [HEADER.format(name=contract_name)]
    for index, cluster in enumerate(c for c in report.clusters if c.verdict == "defect"):
        finding = cluster.representative
        parts.append(
            TEST_TEMPLATE.format(
                ident=_identifier(index, finding.clause, finding.rule_id),
                summary=cluster.summary.replace("\n", " "),
                clause=finding.clause,
                inputs=repr(dict(sorted(finding.inputs.items()))),
                expected=repr(dict(sorted(finding.expected.items()))),
            )
        )
    return "".join(parts)


def _run_tests(source: str, implementation: Implementation) -> tuple[int, int, int, int]:
    namespace: dict[str, Any] = {"__name__": "generated_regression"}
    exec(compile(source, "<regression>", "exec"), namespace)  # noqa: S102 - source is generated by us
    namespace["implementation"] = implementation
    tests = [fn for name, fn in namespace.items() if name.startswith("test_") and callable(fn)]
    passed = failed = errors = 0
    for fn in tests:
        try:
            fn()
            passed += 1
        except AssertionError:
            failed += 1
        except Exception:  # noqa: BLE001
            errors += 1
    return len(tests), passed, failed, errors


def verify_regression(source: str, buggy: Implementation, fixed: Implementation) -> RegressionResult:
    total, _, failed_buggy, errors_buggy = _run_tests(source, buggy)
    _, passed_fixed, _, errors_fixed = _run_tests(source, fixed)
    return RegressionResult(
        tests=total,
        failing_on_buggy=failed_buggy,
        passing_on_fixed=passed_fixed,
        errors=errors_buggy + errors_fixed,
    )
